/** Normalizace klíče: lowercase, bez diakritiky, mezery → _, bez interpunkce. */
export function normKey(s: string): string {
  return s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^\w\s-]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\s/g, "_");
}

/** Najdi mapování pro volný text. Zkusí přesnou shodu, pak základ před " a ". */
export function lookup(map: Record<string, string>, raw: string): string | null {
  const k = normKey(raw);
  if (map[k]) return map[k];
  const base = k.split(/_a_/)[0];
  if (base !== k && map[base]) return map[base];
  return null;
}
